var main = document.getElementById("main");
var homePage = document.getElementById("homePage");
var tracks = document.getElementById("tracks");
var gallery = document.getElementById("gallery");
var creditGrid = document.getElementById("creditGrid");
var lockMessage = document.getElementById("lockMessage");
var slider = document.getElementById("slider");
var lane = document.getElementById("lane");
var expressSquare = document.getElementById("expressSquare");
var trains = [];
var started = false;
var lastTime = 0;
var fareEvaded = false;
var messageTimer = null;
var dragging = false;

function clamp(n, min, max) {
    return Math.max(min, Math.min(n, max));
}



function makeTrains() {
    var width = main.clientWidth;
    var height = main.clientHeight;

    for (var a = 0; a < lines.length; a++) {
        var line = lines[a];

        for (var b = 0; b < line.trains.length; b++) {
            var path = line.trains[b];

            
            var points = [];
            for (var j = 0; j < path.length; j++) {
                points.push({
                    x: clamp(path[j][0] / 100 * width, 40, width - 92),
                    y: clamp(path[j][1] / 100 * height, 60, height - 92)
                });
            }

           
            var track = document.createElementNS("http://www.w3.org/2000/svg", "polyline");
            var pointText = "";
            for (var k = 0; k < points.length; k++) {
                pointText += (points[k].x + 26) + "," + (points[k].y + 26) + " ";
            }
            track.setAttribute("points", pointText);
            tracks.appendChild(track);

            
            var button = document.createElement("button");
            button.className = "train " + line.color;
            if (fareEvaded) {
                button.className = button.className + " locked";
            }
            homePage.appendChild(button);

            var train = {
                button: button,
                line: line,
                points: points,
                x: points[0].x,
                y: points[0].y,
                target: 1,
                direction: 1,
                speed: line.speed,
                stopped: false,
                locked: fareEvaded
            };

            button.style.left = train.x + "px";
            button.style.top = train.y + "px";

            button.onclick = makeClickHandler(train);

            trains.push(train);
        }
    }
}

function makeClickHandler(train) {
    return function () {
        
        if (train.locked) {
            showLockMessage(train);
            return;
        }

        train.stopped = true;
        openStation(train.line);
    };
}


function showLockMessage(train) {
    var left = clamp(train.x, 20, main.clientWidth - 170);

    lockMessage.style.left = left + "px";
    lockMessage.style.top = (train.y - 34) + "px";
    lockMessage.classList.add("show");

    clearTimeout(messageTimer);
    messageTimer = setTimeout(function () {
        lockMessage.classList.remove("show");
    }, 1400);
}

function moveTrain(train, seconds) {
    var goal = train.points[train.target];
    var dx = goal.x - train.x;
    var dy = goal.y - train.y;
    var distance = Math.sqrt(dx * dx + dy * dy);
    var step = train.speed * seconds;

    if (distance <= step) {
        train.x = goal.x;
        train.y = goal.y;
        train.target = train.target + train.direction;

        if (train.target >= train.points.length) {
            train.direction = -1;
            train.target = train.points.length - 2;
        }
        if (train.target < 0) {
            train.direction = 1;
            train.target = 1;
        }
    } else {
        train.x = train.x + dx / distance * step;
        train.y = train.y + dy / distance * step;
    }

    train.button.style.left = train.x + "px";
    train.button.style.top = train.y + "px";
}

function animate(time) {
    var seconds = Math.min((time - lastTime) / 1000, 0.1);
    lastTime = time;

    if (started && main.style.display !== "none") {
        for (var i = 0; i < trains.length; i++) {
            if (!trains[i].stopped) {
                moveTrain(trains[i], seconds);
            }
        }
    }

    requestAnimationFrame(animate);
}



function makeCredits() {
    creditGrid.innerHTML = "";

    for (var i = 0; i < creditPhotos.length; i++) {
        var cell = document.createElement("button");
        cell.className = "credit-cell";

        var picture = document.createElement("img");
        picture.src = creditPhotos[i].file;
        picture.alt = "";
        cell.appendChild(picture);

        cell.onclick = makeCreditHandler(cell, picture, creditPhotos[i].color);

        creditGrid.appendChild(cell);
    }
}

function makeCreditHandler(cell, picture, color) {
    var showingColor = false;

    return function () {
        if (showingColor) {
            
            cell.className = "credit-cell";
            picture.style.display = "block";
            showingColor = false;
        } else {
            
            cell.className = "credit-cell " + color;
            picture.style.display = "none";
            showingColor = true;
        }
    };
}






function setLane(position, smooth) {
    if (smooth) {
        slider.style.transition = "transform 0.6s ease";
        expressSquare.style.transition = "left 0.6s ease";
    } else {
        slider.style.transition = "none";
        expressSquare.style.transition = "none";
    }

    expressSquare.style.left = (position * 100) + "%";
    slider.style.transform = "translateX(" + (-position * 200) + "vw)";
}

expressSquare.addEventListener("pointerdown", function (event) {
    dragging = true;
    expressSquare.classList.add("dragging");
    expressSquare.setPointerCapture(event.pointerId);
});


expressSquare.addEventListener("pointermove", function (event) {
    if (!dragging) {
        return;
    }

    var box = lane.getBoundingClientRect();
    var position = clamp((event.clientX - box.left) / box.width, 0, 1);
    setLane(position, false);
});




function dropSquare() {
    if (!dragging) {
        return;
    }

    dragging = false;
    expressSquare.classList.remove("dragging");

    var current = parseFloat(expressSquare.style.left) / 100;
    var stop = Math.round(current * 2) / 2;
    setLane(stop, true);
}

expressSquare.addEventListener("pointerup", dropSquare);
expressSquare.addEventListener("pointercancel", dropSquare);




function makeGallery(layout) {
    var grid = document.createElement("div");
    grid.className = "gallery-grid";

    for (var i = 0; i < layout.length; i++) {
        for (var j = 0; j < layout[i].length; j++) {
            grid.appendChild(makeCell(layout[i][j]));
        }
    }

    return grid;
}

function makeCell(item) {
    var cell = document.createElement("div");
    cell.className = "cell";

    
    if (item.type === "photo") {
        showGraySquare(cell, item);
    }

    
    if (item.type === "small") {
        var still = document.createElement("div");
        still.className = "gray-square still";
        cell.appendChild(still);
    }

    
    if (item.type === "blank" || item.type === "text") {
        var big = document.createElement("div");
        big.className = "big-square";
        if (item.type === "text") {
            big.textContent = item.text;
        }
        cell.appendChild(big);
    }

    

    return cell;
}


function showGraySquare(cell, item) {
    cell.innerHTML = "";

    var square = document.createElement("button");
    square.className = "gray-square";
    square.onclick = function () {
        showItem(cell, item);
    };

    cell.appendChild(square);
}


function showItem(cell, item) {
    cell.innerHTML = "";

    var picture = document.createElement("img");
    picture.src = item.file;
    picture.onclick = function () {
        showGraySquare(cell, item);
    };

    cell.appendChild(picture);
}




function enterSubway(method) {
    document.getElementById("opening").style.display = "none";
    main.style.display = "block";

    
    fareEvaded = (method === "evade");

    if (fareEvaded) {
        document.getElementById("instruction").textContent = "YOU FOUND ANOTHER WAY IN";
    } else {
        document.getElementById("instruction").textContent = "FIND YOUR TRAIN";
    }

    if (!started) {
        makeTrains();
        started = true;
    }
}


function exitSubway() {
    main.style.opacity = 0;

    setTimeout(function () {
        
        for (var i = 0; i < trains.length; i++) {
            trains[i].button.remove();
        }
        tracks.innerHTML = "";
        trains = [];
        started = false;

        
        for (var j = 0; j < lines.length; j++) {
            lines[j].grid = null;
        }

        
        

        lockMessage.classList.remove("show");
        gallery.innerHTML = "";
        makeCredits();
        setLane(0.5, false);

        main.style.display = "none";
        main.style.opacity = 1;
        document.getElementById("opening").style.display = "flex";
    }, 600);
}


function openStation(story) {
    document.getElementById("stationContent").style.display = "none";
    gallery.style.display = "block";

    
    if (!story.grid) {
        story.grid = makeGallery(story.layout);
    }
    gallery.innerHTML = "";
    gallery.appendChild(story.grid);
    gallery.scrollTop = 0;

    main.style.display = "none";
    document.getElementById("station").style.display = "block";
}

function goBack() {
    document.getElementById("station").style.display = "none";
    main.style.display = "block";
}

